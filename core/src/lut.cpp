// "Lumen Log" curve (applied on Android through Camera2 TONEMAP_CURVE) and a
// matching .cube LUT that converts Lumen Log footage back to Rec.709.
#include <cmath>
#include <cstdio>

#include "common.h"

namespace {
constexpr float kK = 48.f;     // curvature
constexpr float kFoot = 0.05f; // black sits at 5% (leaves footroom)
constexpr float kSpan = 0.90f; // white at 95%
float log2k() { return std::log2(1.f + kK); }

float rec709_oetf(float L) {
  L = lumen::clampf(L, 0.f, 1.f);
  return L < 0.018f ? 4.5f * L : 1.099f * std::pow(L, 0.45f) - 0.099f;
}
}  // namespace

extern "C" float lumen_log_encode(float x) {
  if (!(x > 0.f)) return kFoot;
  if (x >= 1.f) return kFoot + kSpan;
  return kFoot + kSpan * std::log2(1.f + kK * x) / log2k();
}

extern "C" float lumen_log_decode(float y) {
  float t = (y - kFoot) / kSpan;
  if (t <= 0.f) return 0.f;
  if (t >= 1.f) return 1.f;
  return (std::exp2(t * log2k()) - 1.f) / kK;
}

extern "C" int32_t lumen_write_log_lut(const char* path, int32_t size) {
  if (!path || size < 2 || size > 129) return LUMEN_ERR_INVALID_ARG;
  FILE* f = std::fopen(path, "w");
  if (!f) return LUMEN_ERR_IO;
  std::fprintf(f, "# Lumen Log -> Rec.709 (generated by Lumen imaging core %s)\n", LUMEN_CORE_VERSION);
  std::fprintf(f, "TITLE \"Lumen Log to Rec709\"\nLUT_3D_SIZE %d\nDOMAIN_MIN 0 0 0\nDOMAIN_MAX 1 1 1\n", size);
  const float n = float(size - 1);
  for (int b = 0; b < size; ++b)
    for (int g = 0; g < size; ++g)
      for (int r = 0; r < size; ++r) {
        float in[3] = {r / n, g / n, b / n};
        float o[3];
        for (int c = 0; c < 3; ++c) {
          float lin = lumen_log_decode(in[c]);
          float v = rec709_oetf(lin);
          // gentle display contrast so graded-by-LUT footage is not flat
          float a = std::pow(lumen::clampf(v, 0.f, 1.f), 1.08f);
          float bb = std::pow(1.f - lumen::clampf(v, 0.f, 1.f), 1.08f);
          o[c] = a / (a + bb + 1e-9f);
        }
        std::fprintf(f, "%.6f %.6f %.6f\n", o[0], o[1], o[2]);
      }
  return std::fclose(f) == 0 ? LUMEN_OK : LUMEN_ERR_IO;
}
